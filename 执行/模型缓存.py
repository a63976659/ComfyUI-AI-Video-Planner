# -*- coding: utf-8 -*-
"""模型缓存：跨段复用已加载模型，避免重复加载。

进程内 dict，持强引用且进程级永生。⚠️ 与宿主显存策略的关系（Task 9/11 必读）：
ComfyUI 的 model_management.free_memory() 以 sys.getrefcount(model.model) 作为卸载排序
主键（见 comfy/model_management.py）——本模块每多持一份引用，会把该模型排成「最后才被
卸载」。故需主动让出显存或切换 ckpt 时，调用方必须先 清缓存(键)；仅靠 清理显存() 释放不
了被本 dict 钉住的模型。
"""

_已加载 = {}
_缺 = object()  # 区分「键不存在」与「缓存值本身是 None」的哨兵


def 取模型(键: str, 加载函数):
    """键未命中时调用 `加载函数()` 并缓存；命中直接返回缓存实例。

    调用方契约（Task 9 必读）：
        1. 键 必须唯一刻画「可复用性」——至少含 ckpt 标识 + 设备/dtype + 是否已打补丁
           （+ 是否 offload）；缺任一项会导致跨节点假复用（返回不匹配的模型）。
        2. 返回值是共享实例：调用方不得就地 patch / 权重原地改写后再拿另一个键缓存
           第二份，否则同一对象被两条链改花。
        3. 加载函数抛错时不写缓存（异常原样上抛、dict 不留占位），同键可安全重试。
    并发：依赖 ComfyUI 单 prompt_worker 线程串行执行；若将来并行跑段，须由调用方
    （Task 9）保证同键加载串行，本模块不加锁（避免持锁跑数十分钟的模型加载）。
    """
    值 = _已加载.get(键, _缺)
    if 值 is _缺:
        值 = 加载函数()
        _已加载[键] = 值
    return 值


def 清缓存(键: str | None = None):
    """释放模型缓存引用：给定 键 只删该键，None 清空全部；删不存在的键不报错。
    注意：删除仅解除本模块引用，真正回收显存还需持有者释放引用 + 段间 清理显存()。"""
    if 键 is None:
        _已加载.clear()
    else:
        _已加载.pop(键, None)
