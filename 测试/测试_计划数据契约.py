# -*- coding: utf-8 -*-
"""计划数据前后端契约锁（与 测试_常量同步.py 同源模式）。

JS 与 Python 无法共享常量，故「计划数据」功能里**既有后端真源、又有前端镜像**的值各存一份。
漂移不会报错，只会让 UI 与后端行为静默不一致：

- 前端 `非法名字符` 正则 **≠** 后端 `_非法名字符`
  → 前端预校验放过的名，后端 安全名() 拒收 → 用户看到"保存失败"但不知为何；
- 前端 `名最长` **≠** 后端 `_名最长`
  → 前端允许输入 120 字符，后端拒收 → 同上；
- 前端接口路径 **≠** 后端 @routes 路径
  → fetch 404，计划列表永远为空；
- 前端 `直读widget名` **≠** 节点 widget 定义
  → 保存时漏字段 / 加载时写不存在的 widget（静默失败）。

真源恒在 **Python**（后端路由/计划路由.py 与 节点/长视频规划师.py），
前端 网页资源/组件/计划数据.js 是镜像。

⚠️ 锚点匹配次数必须**恰为 1**：0 次 = 前端已重命名/删除，>1 次 = 出现了第二份镜像，
两种情况同步保证都已失效，一律**判失败而非跳过**——静默跳过等于没有锁。
只有 JS 文件整个不存在（如不完整检出）才 skip，见 `js源`。
"""
import re
from pathlib import Path

import pytest

comfy_api = pytest.importorskip("comfy_api")   # 长视频规划师 依赖 V3 io；缺宿主则整文件跳过
长视频规划师 = pytest.importorskip("节点.长视频规划师")
计划路由 = pytest.importorskip("后端路由.计划路由")

_插件根 = Path(__file__).resolve().parents[1]
_计划数据js = _插件根 / "网页资源" / "组件" / "计划数据.js"


@pytest.fixture(scope="module")
def js源():
    """前端源文本。utf-8-sig：容忍 BOM，免得首行锚点被 \\ufeff 顶掉。"""
    if not _计划数据js.exists():
        pytest.skip(f"未找到前端源文件：{_计划数据js}")
    return _计划数据js.read_text(encoding="utf-8-sig")


def _唯一(源, 模式, 名):
    """按正则在 JS 源里取捕获组，要求**恰好一处**匹配（0 或 >1 均判失败，理由见模块 docstring）。"""
    命中 = re.findall(模式, 源)
    assert len(命中) == 1, (
        f"{名}：前端锚点应恰好匹配 1 次，实际 {len(命中)} 次"
        f"（0=已重命名/删除，>1=出现第二份镜像，同步保证均已失效）。模式={模式!r}"
    )
    return 命中[0]


# ---------- 1. 非法名字符正则：前后端模式逐字对齐 ----------

def test_非法名字符正则_前后端同步(js源):
    """前端 `const 非法名字符 = /.../` 与后端 `_非法名字符 = re.compile(r'...')` 的模式必须逐字相等。

    JS 正则字面量 `/[\\\\/:*?"<>|\\x00-\\x1f]/` 与 Python 原始字符串 `r'[\\\\/:*?"<>|\\x00-\\x1f]'`
    在**模式内容**上完全一致（都是字符类：反斜杠/斜杠/冒号/星/问号/双引号/小于/大于/竖线/控制字符）。
    漂移会让前端预校验与后端 安全名() 判定不一致：前端放过的名后端拒收，用户看到"保存失败"但不知为何。
    """
    # 前端：const 非法名字符 = /[...]/;  → 捕获 / 与 / 之间的模式
    前端模式 = _唯一(js源, r"const\s+非法名字符\s*=\s*/(.+?)/\s*;", "非法名字符正则")
    # 后端：_非法名字符 = re.compile(r'[...]')  → 捕获引号内的模式
    后端模式 = 计划路由._非法名字符.pattern
    assert 前端模式 == 后端模式, (
        f"非法名字符正则漂移：\n"
        f"  前端 /{前端模式}/\n"
        f"  后端 r'{后端模式}'\n"
        f"真源在 Python（后端路由/计划路由.py 的 _非法名字符），"
        f"前端 网页资源/组件/计划数据.js 是镜像——改一处必须同步另一处。"
    )


# ---------- 2. 名最长：前后端数值对齐 ----------

def test_名最长_前后端同步(js源):
    """前端 `const 名最长 = 100` 与后端 `_名最长 = 100` 必须逐值相等。

    漂移会让前端允许输入的名字长度与后端拒收阈值不一致：前端放过 120 字符，后端拒收 →
    用户看到"保存失败"但不知为何（前端预校验本应提前拦截）。
    """
    前端 = int(_唯一(js源, r"const\s+名最长\s*=\s*(\d+)", "名最长"))
    后端 = 计划路由._名最长
    assert 前端 == 后端, (
        f"名最长漂移：前端 {前端} ≠ 后端 {后端}。"
        f"真源在 Python（后端路由/计划路由.py 的 _名最长），"
        f"前端 网页资源/组件/计划数据.js 是镜像——改一处必须同步另一处。"
    )


# ---------- 3. 接口路径：前端 fetch URL 与后端 @routes 装饰器对齐 ----------

@pytest.mark.parametrize("前端常量名,后端路径", [
    ("列表接口", "/lvp/plan/list"),
    ("加载接口", "/lvp/plan/load"),
    ("保存接口", "/lvp/plan/save"),
], ids=["list", "load", "save"])
def test_接口路径_前后端同步(js源, 前端常量名, 后端路径):
    """前端 `const 列表接口 = "/lvp/plan/list"` 等与后端 `@routes.get("/lvp/plan/list")` 必须逐字相等。

    漂移会让 fetch 404，计划列表永远为空 / 保存永远失败，且错误信息是浏览器通用的
    "HTTP 404"，用户与开发者都看不出是路径拼写不一致。
    """
    前端 = _唯一(js源, rf'const\s+{前端常量名}\s*=\s*"([^"]+)"', 前端常量名)
    assert 前端 == 后端路径, (
        f"{前端常量名} 漂移：前端 {前端!r} ≠ 后端 {后端路径!r}。"
        f"真源在 Python（后端路由/计划路由.py 的 @routes 装饰器），"
        f"前端 网页资源/组件/计划数据.js 是镜像——改一处必须同步另一处。"
    )


# ---------- 4. 直读widget名：前端数组与节点 widget 定义对齐 ----------

def test_直读widget名_前后端同步(js源):
    """前端 `const 直读widget名 = ["帧率", "步数", "采样器", "调度器"]` 里的每个名字
    必须在节点 长视频规划师.py 的 inputs 里有对应 `io.*.Input("名", ...)` 定义。

    漂移会让保存时漏字段（前端收了但节点没这个 widget → undefined 被过滤掉）或
    加载时写不存在的 widget（写值() 返回 false，静默失败）——用户加载计划后发现
    "帧率/步数/采样器/调度器 没恢复"，但看不出是名字拼写不一致。

    注意：这 4 个 widget 是**普通数值/枚举**，不走 真源 的 JSON 序列化通道
    （任务类型/全局提示词/输出分辨率/百万像素/参考共用/尾帧锚定/运行选择/时间轴/参考素材
    那 9 个走 真源.读/写，字段名由 节点桥.js 的 真源 对象锁定，不在此测范围）。
    """
    # 前端：const 直读widget名 = ["a", "b", ...];  → 捕获方括号内的全部内容
    前端串 = _唯一(js源, r'const\s+直读widget名\s*=\s*\[([^\]]+)\]', "直读widget名")
    # 解析 JS 数组字面量：["帧率", "步数", ...] → Python list
    前端名 = re.findall(r'"([^"]+)"', 前端串)
    assert len(前端名) == 4, f"直读widget名 应恰好 4 项，实际 {len(前端名)}：{前端名}"

    # 后端：从节点定义源码里扫 io.*.Input("名", ...)
    节点源 = (_插件根 / "节点" / "长视频规划师.py").read_text(encoding="utf-8-sig")
    后端名 = set(re.findall(r'io\.\w+\.Input\(\s*"([^"]+)"', 节点源))

    for 名 in 前端名:
        assert 名 in 后端名, (
            f"直读widget名 漂移：前端列了 {名!r}，但节点 长视频规划师.py 里没有 "
            f"io.*.Input({名!r}, ...) 定义。前端名列表={前端名}，节点 widget 名集合={sorted(后端名)}。"
            f"真源在 Python（节点/长视频规划师.py），前端 网页资源/组件/计划数据.js 是镜像。"
        )


# ---------- 5. 计划文件夹名：后端常量与前端 UI 文本对齐 ----------

def test_计划文件夹名_前后端同步(js源):
    """后端 `_计划文件夹名 = "计划数据"` 必须与前端 UI 里显示的"计划数据"文本一致。

    这条锁的是**用户可见的命名一致性**：后端把文件存到 `插件根/计划数据/`，前端 UI 标签
    也叫"计划数据"，tooltip 里也提"插件根/计划数据/<名>.json"。漂移会让用户看着 UI 叫
    "计划数据"但去磁盘上找"计划/"找不到，或反之。

    前端锚点：`组.textContent = "计划数据"`（UI 标签）与 `组.title` 里的"计划数据"（tooltip）。
    只锁 textContent 那一条（恰好 1 次），tooltip 里可能出现多次不锁。
    """
    前端 = _唯一(js源, r'组\.textContent\s*=\s*"([^"]+)"', "计划文件夹名-UI标签")
    后端 = 计划路由._计划文件夹名
    assert 前端 == 后端, (
        f"计划文件夹名漂移：前端 UI 标签 {前端!r} ≠ 后端 _计划文件夹名 {后端!r}。"
        f"真源在 Python（后端路由/计划路由.py），前端 网页资源/组件/计划数据.js 是镜像。"
    )
