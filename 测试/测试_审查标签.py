# -*- coding: utf-8 -*-
"""前端「审查标签 / 悬空降级」跨栈契约锁。

`网页资源/组件/提示词编辑器.js` 的「审查标签」按钮：把没有对应上传素材的悬空
`<Picture/Video/Audio N>` **二次确认后**降级为纯文字 `[...]`。它修的是真实报过的错
（`校验标签: 提示词引用第 1 个视频，但该段只有 0 个`），但正确性全押在几条**跨栈隐性契约**
上——漂移不会报错，只会让「点了审查、生成照样炸」或「二次确认形同虚设」：

  C1 降级产物必须**不再**被后端 `提取标签`/`校验标签` 认作保留 token（否则降级白做，仍抛原错）；
  C2 悬空判定的「标签英文名 → 素材槽」映射必须与后端 `_标签到槽` 同值（否则按错槽位数判断，
     把有素材的当悬空误删、或把悬空的当有素材放过）；
  C3 必须**先二次确认再改写**（用户明确要求）：JS 源里 `弹确认` 调用须在 `设值(新文)` 之前，
     且取消分支 `if (!确认)` 在两者之间 return。

真源：C1 的判定权威在 Python（`提取标签`/`校验标签` 说了算）；C2 后端 `_标签到槽` 为真源、
前端小写键为镜像；C3 仅前端源文本可验。本项目不在 pytest 里跑 JS，故前端半边一律用
「正则锚点扫源文本」——锚点须**恰好匹配 1 次**（0=已删/改名，>1=出现第二份，锁均失效），
理由同 `测试_常量同步.py`。
"""
import re
from pathlib import Path

import pytest

from 执行.参考素材 import _标签到槽, 解析槽位, 提取标签, 校验标签

_插件根 = Path(__file__).resolve().parents[1]
_提示词编辑器 = _插件根 / "网页资源" / "组件" / "提示词编辑器.js"


@pytest.fixture(scope="module")
def js源():
    """前端源文本。utf-8-sig：容忍 BOM，免得首行锚点被 \\ufeff 顶掉。"""
    if not _提示词编辑器.exists():
        pytest.skip(f"未找到前端源文件：{_提示词编辑器}")
    return _提示词编辑器.read_text(encoding="utf-8-sig")


def _唯一(源, 模式, 名):
    """按正则在 JS 源里取匹配，要求**恰好一处**（0 或 >1 均判失败）。"""
    命中 = re.findall(模式, 源)
    assert len(命中) == 1, (
        f"{名}：前端锚点应恰好匹配 1 次，实际 {len(命中)} 次"
        f"（0=已删/改名，>1=出现第二份，同步保证均失效）。模式={模式!r}"
    )
    return 命中[0]


# ---------- C1：降级产物对后端 inert（直接锁住用户报的那个错不再复现）----------

@pytest.mark.parametrize("类,槽", [("Picture", "图片"), ("Video", "视频"), ("Audio", "音频")])
def test_降级产物_后端不再当引用(类, 槽):
    """`<X 1>` 是活 token（空素材会抛用户报的错）；`[X 1]` 必须 inert（审查标签降级后不再抛）。

    这条把「用户原始报错」与「审查标签达成的效果」钉在一起：只要 提取标签/校验标签 的判定不变，
    降级前必抛、降级后必不抛就恒成立——是 C1 的后端权威半边。
    """
    空槽 = 解析槽位({})
    # 降级前：尖括号形式被认作引用，空素材 → 校验标签 抛（== 用户原始报错路径）
    assert 提取标签(f"<{类} 1>") == [(槽, 1)]
    with pytest.raises(ValueError, match="但该段只有 0 个"):
        校验标签(f"<{类} 1>", 空槽)
    # 降级后：方括号形式 提取标签 不认、校验标签 不抛（== 审查标签达成的效果）
    assert 提取标签(f"[{类} 1]") == []
    校验标签(f"[{类} 1]", 空槽)   # 不应抛


def test_JS降级确产方括号形式(js源):
    """C1 的前端半边：锁 JS 把 `<X>` 换成 `[X]`（`slice(1,-1)` 去尖括号、外面包方括号）。

    若这里漂移（如改回尖括号、或换成别的记号），上面 test_降级产物 的后端断言仍在、但前端已不再
    产出那个 inert 形式 → 降级失效。两边合起来才锁死「前端产出的正是后端不认的那个形式」。
    """
    _唯一(js源, r'"\["\s*\+\s*整串\.slice\(1,\s*-1\)\s*\+\s*"\]"', "降级为方括号")


# ---------- C2：悬空判定的「标签 → 槽」映射与后端同源 ----------

def test_标签到槽_前后端镜像(js源):
    """前端 `标签到槽`（小写英文键）必须 == 后端 `_标签到槽`（首字母大写键）的小写化。

    审查标签据此把 `<Video N>` 归到「视频」槽查素材数；映射漂移 → 按错槽位数判断悬空，
    误删有素材的引用、或放过真悬空的。真源在 `执行/参考素材.py`，前端是镜像（同 J3 精神）。
    """
    块 = _唯一(js源, r"标签到槽\s*=\s*\{([^}]*)\}", "标签到槽映射")
    前端 = dict(re.findall(r'(\w+)\s*:\s*"([^"]+)"', 块))
    后端小写 = {k.lower(): v for k, v in _标签到槽.items()}
    assert 前端 == 后端小写, (
        f"标签→槽 映射漂移：前端 {前端} ≠ 后端小写 {后端小写}。"
        f"真源在 执行/参考素材.py `_标签到槽`，前端 提示词编辑器.js `标签到槽` 是镜像——改一处须同步另一处。"
    )


# ---------- C3：先二次确认、后改写（用户明确要求）----------

def test_二次确认先于降级改写(js源):
    """锁 JS 源里顺序：`await 弹确认(...)` → `if (!确认) return` → `设值(新文)`。

    只要 弹确认 调用在 设值(新文) 之前、且取消分支在两者之间 return，即满足「确认才改写」。
    纯源文本顺序检查（本项目不在 pytest 里跑 JS）；三锚点各须恰好出现 1 次，防骨架被拆/被复制。
    """
    确认call, 取消guard, 改写 = "await 弹确认(", "if (!确认)", "设值(新文)"
    for 锚 in (确认call, 取消guard, 改写):
        assert js源.count(锚) == 1, (
            f"审查标签 二次确认锚点 {锚!r} 应恰好出现 1 次，实际 {js源.count(锚)} 次"
        )
    位确认, 位取消, 位改写 = js源.find(确认call), js源.find(取消guard), js源.find(改写)
    assert 位确认 < 位取消 < 位改写, (
        f"二次确认顺序被破坏：须 弹确认({位确认}) < if(!确认)return({位取消}) < 设值(新文)({位改写})，"
        f"否则会在用户确认前就改写提示词（用户要求「二次确认再降级」）。"
    )
